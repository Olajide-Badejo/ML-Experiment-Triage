"""Generate the LaTeX tables and figure data the reports compile from.

Every number in the PDFs comes through here, from the database, so there is no
path by which a report can state a figure that was not computed. Nothing is
typed into the `.tex` chapters by hand.

Figures are emitted as pgfplots data files plus a small `.tex` wrapper rather
than as raster images. That keeps the plots vector, keeps them typeset in the
document's own font, and avoids adding a Python image toolchain to a project
that does not otherwise need one.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from triage.analysis.comparison import (
    ComparisonConfig,
    compare_all,
    group_by_variant,
    window_statistic,
)
from triage.analysis.regression import RegressionConfig, TriageReport, classify
from triage.analysis.sensitivity import analyse
from triage.calibration import GATES, UNIFORMITY, WEAK_MODE_COST
from triage.core.store import Store
from triage.progress import track

ROOT = Path(__file__).resolve().parent.parent
FIGURES = ROOT / "report" / "figures"
TABLES = ROOT / "report" / "tables"
BASELINE = "lr0.0010_bs32"

MAX_PLOT_POINTS = 300

# All measured numbers come from triage.calibration, which is the single source
# the README, the HTML footer, these tables and the figures all read.
CALIBRATION_ROWS = [(gate.name, gate.result, gate.sample, gate.gate) for gate in GATES]

WEAK_MODE_ROWS = [
    (f"{sigma:.2f}", f"{weak * 100:.1f} percent", f"{strong * 100:.1f} percent")
    for sigma, weak, strong in WEAK_MODE_COST
]

UNIFORMITY_ROWS = [(f"{threshold:.2f}", f"{measured:.3f}") for threshold, measured in UNIFORMITY]


def escape(text: str) -> str:
    """Make a string safe to drop into LaTeX body text."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for character, replacement in replacements.items():
        text = text.replace(character, replacement)
    return text


def write(path: Path, lines: list[str]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def format_p(value: float) -> str:
    return "$<0.0001$" if value < 0.0001 else f"{value:.4f}"


# ------------------------------------------------------------------- tables


def verdict_table(report: TriageReport) -> list[str]:
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tabular}{llrrrl}",
        r"\toprule",
        r"Candidate & Metric & Change & $p$ & $p$ adj. & Verdict \\",
        r"\midrule",
    ]
    for finding in report.findings:
        result = finding.result
        mode = r"\,$\dagger$" if result.is_weak_mode else ""
        lines.append(
            f"{escape(result.candidate)}{mode} & {escape(result.tag)} & "
            f"{result.relative_effect_pct:+.2f}\\% & {format_p(result.p_value)} & "
            f"{format_p(finding.adjusted_p)} & {escape(finding.verdict)} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return lines


def run_table(experiments: list, config: ComparisonConfig) -> list[str]:
    variants = group_by_variant(experiments)
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tabular}{llrrr}",
        r"\toprule",
        r"Condition & Log format & Seeds & Final loss & Spread \\",
        r"\midrule",
    ]
    for name, runs in variants.items():
        values = [
            window_statistic(run.series("val/loss"), config) for run in runs if run.has("val/loss")
        ]
        if not values:
            continue
        spread = float(np.std(values, ddof=1)) if len(values) > 1 else 0.0
        formats = ", ".join(sorted({run.source_format for run in runs}))
        marker = r" (baseline)" if name == BASELINE else ""
        lines.append(
            f"{escape(name)}{marker} & {escape(formats)} & {len(runs)} & "
            f"{np.mean(values):.4f} & {spread:.4f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return lines


def sensitivity_table(results: list) -> list[str]:
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"Parameter & Metric & Spearman $\rho$ & $p$ & $n$ runs & Distinct values \\",
        r"\midrule",
    ]
    for item in results:
        lines.append(
            f"{escape(item.parameter)} & {escape(item.tag)} & {item.correlation:+.3f} & "
            f"{format_p(item.p_value)} & {item.n_runs} & {item.n_distinct_values} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return lines


def calibration_table() -> list[str]:
    """Three columns, not four, and the first one wraps.

    As four separate columns this table was wider than the text block and the
    gate column ran off the page. The sample size belongs with the result it
    describes rather than in a column of its own, and `tabularx` on the first
    column guarantees the table can never exceed the line width again.
    """
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tabularx}{\linewidth}{@{}>{\raggedright\arraybackslash}X l l@{}}",
        r"\toprule",
        r"Measurement & Result & Gate \\",
        r"\midrule",
    ]
    lines += [
        f"{escape(name)} & {escape(result)}, {escape(sample)} & {escape(gate)} \\\\"
        for name, result, sample, gate in CALIBRATION_ROWS
    ]
    lines += [r"\bottomrule", r"\end{tabularx}"]
    return lines


def weak_mode_table() -> list[str]:
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Seed standard deviation & Window block mode & Seed replicated mode \\",
        r"\midrule",
    ]
    lines += [f"{a} & {escape(b)} & {escape(c)} \\\\" for a, b, c in WEAK_MODE_ROWS]
    lines += [r"\bottomrule", r"\end{tabular}"]
    return lines


def uniformity_table() -> list[str]:
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tabular}{rr}",
        r"\toprule",
        r"Nominal threshold & Measured rejection rate \\",
        r"\midrule",
    ]
    lines += [f"{a} & {b} \\\\" for a, b in UNIFORMITY_ROWS]
    lines += [r"\bottomrule", r"\end{tabular}"]
    return lines


# ------------------------------------------------------------------ figures


def slug(text: str) -> str:
    return text.replace("/", "-").replace("_", "-").replace(".", "p")


def curve_data(experiments: list, tag: str, config: ComparisonConfig) -> dict[str, Path]:
    """One pgfplots table per condition: step, mean, low, high across seeds."""
    written: dict[str, Path] = {}
    for name, runs in group_by_variant(experiments).items():
        usable = [run for run in runs if run.has(tag)]
        if not usable:
            continue
        reference = max(usable, key=lambda run: len(run.series(tag))).series(tag)
        grid = reference.steps.astype(np.float64)
        stacked = np.vstack(
            [
                np.interp(
                    grid,
                    run.series(tag).steps.astype(np.float64),
                    run.series(tag).smoothed(config.smoothing_window),
                )
                for run in usable
            ]
        )
        stride = max(1, int(np.ceil(grid.size / MAX_PLOT_POINTS)))
        rows = ["step mean low high"]
        rows += [
            f"{grid[i]:.0f} {stacked[:, i].mean():.6f} "
            f"{stacked[:, i].min():.6f} {stacked[:, i].max():.6f}"
            for i in range(0, grid.size, stride)
        ]
        written[name] = write(FIGURES / f"{slug(tag)}-{slug(name)}.dat", rows)
    return written


# Reference categorical palette, as named colours the figure wrapper defines.
FIGURE_COLOURS = ("seriesA", "seriesB", "seriesC", "seriesD", "seriesE", "seriesF")


def curve_figure(tag: str, data: dict[str, Path], ylabel: str) -> list[str]:
    lines = [
        "% Generated by scripts/gen_report_assets.py. Do not edit.",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  width=\linewidth, height=6.2cm,",
        f"  xlabel={{training step}}, ylabel={{{escape(ylabel)}}},",
        r"  legend style={font=\scriptsize, at={(0.5,1.03)}, anchor=south,"
        r" legend columns=3, draw=none, fill=none},",
        r"  tick label style={font=\scriptsize},",
        r"  label style={font=\small},",
        r"  grid=major, grid style={line width=0.2pt, draw=gridgrey},",
        r"  axis line style={draw=axisgrey},",
        r"  xmin=0,",
        r"]",
    ]
    for index, (name, path) in enumerate(sorted(data.items())):
        colour = "baselinegrey" if name == BASELINE else FIGURE_COLOURS[index % len(FIGURE_COLOURS)]
        style = "dashed" if name == BASELINE else "solid"
        relative = path.relative_to(ROOT / "report").as_posix()
        lines += [
            rf"\addplot [name path=lo{index}, draw=none, forget plot]"
            rf" table [x=step, y=low] {{{relative}}};",
            rf"\addplot [name path=hi{index}, draw=none, forget plot]"
            rf" table [x=step, y=high] {{{relative}}};",
            rf"\addplot [{colour}, opacity=0.15, forget plot] fill between"
            rf" [of=lo{index} and hi{index}];",
            rf"\addplot [{colour}, {style}, line width=1pt, mark=none]"
            rf" table [x=step, y=mean] {{{relative}}};",
            rf"\addlegendentry{{{escape(name)}}}",
        ]
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    return lines


# --------------------------------------------------------------------- main


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--database",
        default=str(ROOT / "experiments" / "demo" / "triage.db"),
        help="database to build the report assets from",
    )
    parser.add_argument("--baseline", default=BASELINE, help="baseline condition")
    parser.add_argument("--quiet", action="store_true", help="no progress output")
    args = parser.parse_args()

    database = Path(args.database)
    if not database.exists():
        raise SystemExit(f"no database at {database}; run `make demo` first")

    comparison_config = ComparisonConfig()
    regression_config = RegressionConfig()
    with Store(database) as store:
        experiments = store.load_all()
        stats = store.statistics()
    if not experiments:
        raise SystemExit(f"{database} holds no runs")

    results = compare_all(experiments, args.baseline, config=comparison_config)
    report = TriageReport(
        findings=classify(results, regression_config),
        config=regression_config,
        baseline=args.baseline,
    )
    sensitivity = analyse(experiments, config=comparison_config)

    written: list[Path] = []
    tasks = [
        ("verdicts", lambda: verdict_table(report)),
        ("runs", lambda: run_table(experiments, comparison_config)),
        ("sensitivity", lambda: sensitivity_table(sensitivity)),
        ("calibration", calibration_table),
        ("weak_mode", weak_mode_table),
        ("uniformity", uniformity_table),
    ]
    for name, build in track(tasks, "tables", enabled=not args.quiet, every=2):
        written.append(write(TABLES / f"{name}.tex", build()))

    labels = {"val/loss": "validation loss", "val/accuracy": "validation accuracy"}
    tags = sorted({tag for run in experiments for tag in run.tags})
    for tag in track(tags, "figures", enabled=not args.quiet, every=1):
        data = curve_data(experiments, tag, comparison_config)
        written.append(
            write(
                FIGURES / f"{slug(tag)}-curves.tex", curve_figure(tag, data, labels.get(tag, tag))
            )
        )

    # Facts the prose interpolates, so no number is ever typed into a chapter.
    facts = {
        "runs": stats["runs"],
        "series": stats["series"],
        "points": stats["points"],
        "database_kb": round(stats["database_bytes"] / 1024),
        "compression_ratio": round(stats["compression_ratio"], 1),
        "conditions": len(group_by_variant(experiments)),
        "comparisons": len(report.findings),
        "regressions": len(report.regressions),
        "improvements": len(report.improvements),
        "best_candidate": report.best_candidate or "none",
        "baseline": args.baseline,
        "permutation_seed": comparison_config.seed,
        "statistic": comparison_config.describe(),
        "gates": regression_config.describe(),
    }
    written.append(write(TABLES / "facts.json", [json.dumps(facts, indent=2)]))
    write(
        TABLES / "facts.tex",
        ["% Generated by scripts/gen_report_assets.py. Do not edit."]
        + [
            rf"\newcommand{{\fact{key.replace('_', '')}}}{{{escape(str(value))}}}"
            for key, value in facts.items()
        ],
    )

    print(f"wrote {len(written) + 1} report assets from {database.name}")
    print(f"  tables: {TABLES.relative_to(ROOT)}")
    print(f"  figures: {FIGURES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
