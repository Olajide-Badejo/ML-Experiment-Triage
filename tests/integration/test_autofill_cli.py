@pytest.mark.slow
def test_the_full_sweep_fits_in_the_time_budget(corpus: Path, tmp_path: Path) -> None:
    """5.2: the full demo grid trains on CPU in under two minutes.

    Marked slow because it is the whole grid; the number it prints is the one
    quoted in `docs/autofill.md`.
    """
    import time

    started = time.perf_counter()
    assert (
        main(["autofill", "sweep", "--data", str(corpus), "--out", str(tmp_path / "full")])
        == EXIT_OK
    )
    elapsed = time.perf_counter() - started
    print(f"\nfull autofill sweep: {elapsed:.1f} s for 30 runs")
    assert elapsed < 120, elapsed
