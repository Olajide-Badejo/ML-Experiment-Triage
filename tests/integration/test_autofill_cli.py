def test_evaluate_compares_the_two_engines_seed_replicated(corpus: Path, tmp_path: Path) -> None:
    """Acceptance criterion 2, as a verdict from this tool's own comparison."""
    runs = tmp_path / "trained"
    assert (
        main(
            [
                "autofill",
                "train",
                "--data",
                str(corpus),
                "--out",
                str(runs),
                "--seed",
                "0",
                "--epochs",
                "6",
            ]
        )
        == EXIT_OK
    )
    weights = next(runs.glob("*/weights.npz"))

    out = tmp_path / "eval"
    assert (
        main(
            [
                "autofill",
                "evaluate",
                "--data",
                str(corpus),
                "--weights",
                str(weights),
                "--bootstrap",
                "5",
                "--locale",
                "de_DE",
                "--out",
                str(out),
            ]
        )
        == EXIT_OK
    )
    database = tmp_path / "engines.db"
    assert main(["ingest", str(out / "runs"), "--database", str(database), "--quiet"]) == EXIT_OK

    import argparse

    from triage.cli import analyse_database

    args = argparse.Namespace(
        database=str(database),
        baseline="rules_de_DE_val",
        tags=["eval/macro_f1"],
        window_fraction=0.10,
        window_minimum=20,
        permutations=10000,
        alpha=0.05,
        practical_threshold=None,
        practical_threshold_absolute=None,
        fdr=0.05,
        seed=20260101,
        higher_is_better=None,
        lower_is_better=None,
    )
    analysis = analyse_database(args, sensitivity=False)
    findings = [f for f in analysis.report.findings if f.result.candidate == "ngram_de_DE_val"]
    assert len(findings) == 1
    finding = findings[0]
    assert not finding.result.is_weak_mode, "five replicates must give the seed replicated mode"
    assert finding.result.higher_is_better
    assert finding.result.effect > 0.05, finding.result.effect
    assert finding.adjusted_p <= 0.05, finding.adjusted_p


