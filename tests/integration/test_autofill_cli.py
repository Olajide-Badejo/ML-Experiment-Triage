"""`triage autofill` end to end, and the sweep landing in the existing tool.

Acceptance criterion 1 is the point of this file: the sweep is generated by one
command, ingested by the command that already existed, and compared by the
command that already existed, with no flag naming autofill anywhere in the last
two. The test therefore drives `triage.cli.main` with real argument lists rather
than calling the library, because a contract that only holds when a Python
caller assembles it by hand is not the contract that was asked for.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from triage.cli import EXIT_OK, EXIT_USAGE, main


@pytest.fixture(scope="module")
def corpus(tmp_path_factory: pytest.TempPathFactory) -> Path:
    root = tmp_path_factory.mktemp("autofill")
    data = root / "data"
    assert (
        main(["autofill", "generate", "--out", str(data), "--n-fields", "1600", "--seed", "0"])
        == EXIT_OK
    )
    return data


def test_generate_writes_the_splits_the_pages_and_the_metadata(corpus: Path) -> None:
    for name in ("fields.train.jsonl", "fields.val.jsonl", "fields.test.jsonl", "meta.json"):
        assert (corpus / name).exists(), name
    pages = sorted(p.name for p in (corpus / "pages").glob("*.html"))
    assert len(pages) == 6
    assert json.loads((corpus / "meta.json").read_text(encoding="utf-8"))["seed"] == 0


def test_generate_honours_a_single_locale(tmp_path: Path) -> None:
    out = tmp_path / "english"
    assert (
        main(["autofill", "generate", "--out", str(out), "--locale", "en_US", "--n-fields", "300"])
        == EXIT_OK
    )
    meta = json.loads((out / "meta.json").read_text(encoding="utf-8"))
    assert set(meta["locales"]) == {"en_US"}
    assert len(list((out / "pages").glob("*.html"))) == 3


def test_train_writes_one_ingestible_run(corpus: Path, tmp_path: Path) -> None:
    runs = tmp_path / "runs"
    assert (
        main(
            [
                "autofill",
                "train",
                "--data",
                str(corpus),
                "--out",
                str(runs),
                "--lr",
                "0.1",
                "--batch-size",
                "64",
                "--l2",
                "0.0001",
                "--seed",
                "2",
                "--epochs",
                "3",
            ]
        )
        == EXIT_OK
    )
    directories = sorted(p for p in runs.iterdir() if p.is_dir())
    assert len(directories) == 1
    assert (directories[0] / "config.json").exists()
    assert (directories[0] / "metrics.jsonl").exists()
    assert (directories[0] / "weights.npz").exists()
    assert main(["ingest", str(runs), "--database", str(tmp_path / "t.db"), "--quiet"]) == EXIT_OK


def test_the_sweep_grid_is_the_one_the_specification_names() -> None:
    from triage.autofill.sweep import SWEEP_GRID, SWEEP_L2, SWEEP_LEARNING_RATES, SWEEP_SEEDS

    assert SWEEP_LEARNING_RATES == (0.03, 0.1, 0.3)
    assert SWEEP_L2 == (0.0, 1e-4)
    assert SWEEP_SEEDS == (0, 1, 2, 3, 4)
    assert len(SWEEP_GRID) == 30


def test_the_sweep_drops_into_ingest_and_compare_with_no_autofill_flag(
    corpus: Path, tmp_path: Path
) -> None:
    """Acceptance criterion 1, driven through the command line.

    A reduced grid: three seeds and three epochs, so the assertion is about the
    plumbing rather than about waiting. The full grid is timed by
    `test_the_full_sweep_fits_in_the_time_budget`.
    """
    runs = tmp_path / "sweep"
    database = tmp_path / "sweep.db"
    assert (
        main(
            [
                "autofill",
                "sweep",
                "--data",
                str(corpus),
                "--out",
                str(runs),
                "--seeds",
                "3",
                "--epochs",
                "3",
            ]
        )
        == EXIT_OK
    )
    assert len(sorted(p for p in runs.iterdir() if p.is_dir())) == 18
    assert (runs / "sweep.json").exists()
    assert (runs / "best.npz").exists()

    assert main(["ingest", str(runs), "--database", str(database), "--quiet"]) == EXIT_OK
    assert (
        main(
            [
                "compare",
                "--database",
                str(database),
                "--baseline",
                "lr0.03_l20",
                "--quiet",
            ]
        )
        == EXIT_OK
    )


def test_the_sweep_summary_names_the_best_condition(corpus: Path, tmp_path: Path) -> None:
    runs = tmp_path / "sweep2"
    assert (
        main(
            [
                "autofill",
                "sweep",
                "--data",
                str(corpus),
                "--out",
                str(runs),
                "--seeds",
                "2",
                "--epochs",
                "2",
            ]
        )
        == EXIT_OK
    )
    summary = json.loads((runs / "sweep.json").read_text(encoding="utf-8"))
    assert summary["n_runs"] == 12
    assert summary["best"]["variant"] in {
        f"lr{lr:g}_l2{l2:g}" for lr in (0.03, 0.1, 0.3) for l2 in (0.0, 1e-4)
    }
    assert summary["seconds"] > 0
    assert summary["grid"]["learning_rate"] == [0.03, 0.1, 0.3]


def test_evaluate_writes_both_shapes_and_the_outcomes_ingest_without_a_flag(
    corpus: Path, tmp_path: Path
) -> None:
    """Acceptance criteria 3 and 4, driven through the command line."""
    runs = tmp_path / "trained"
    assert (
        main(
            [
                "autofill",
                "train",
                "--data",
                str(corpus),
                "--out",
                str(runs),
                "--seed",
                "0",
                "--epochs",
                "4",
            ]
        )
        == EXIT_OK
    )
    weights = next(runs.glob("*/weights.npz"))

    out = tmp_path / "eval"
    assert (
        main(
            [
                "autofill",
                "evaluate",
                "--data",
                str(corpus),
                "--weights",
                str(weights),
                "--policy",
                "model",
                "--bootstrap",
                "3",
                "--locale",
                "de_DE",
                "--out",
                str(out),
            ]
        )
        == EXIT_OK
    )
    calibration = json.loads((out / "calibration.json").read_text(encoding="utf-8"))
    assert calibration["metrics"]["val/ece_post"] < calibration["metrics"]["val/ece_pre"]

    database = tmp_path / "outcomes.db"
    assert (
        main(["ingest", str(out / "outcomes"), "--database", str(database), "--quiet"]) == EXIT_OK
    )

    from triage.core.store import Store

    with Store.open_read_only(str(database)) as store:
        assert store.outcome_run_ids()


def test_evaluate_compares_the_two_engines_seed_replicated(corpus: Path, tmp_path: Path) -> None:
    """Acceptance criterion 2, as a verdict from this tool's own comparison."""
    runs = tmp_path / "trained"
    assert (
        main(
            [
                "autofill",
                "train",
                "--data",
                str(corpus),
                "--out",
                str(runs),
                "--seed",
                "0",
                "--epochs",
                "6",
            ]
        )
        == EXIT_OK
    )
    weights = next(runs.glob("*/weights.npz"))

    out = tmp_path / "eval"
    assert (
        main(
            [
                "autofill",
                "evaluate",
                "--data",
                str(corpus),
                "--weights",
                str(weights),
                "--bootstrap",
                "5",
                "--locale",
                "de_DE",
                "--out",
                str(out),
            ]
        )
        == EXIT_OK
    )
    database = tmp_path / "engines.db"
    assert main(["ingest", str(out / "runs"), "--database", str(database), "--quiet"]) == EXIT_OK

    import argparse

    from triage.cli import analyse_database

    args = argparse.Namespace(
        database=str(database),
        baseline="rules_de_DE_val",
        tags=["eval/macro_f1"],
        window_fraction=0.10,
        window_minimum=20,
        permutations=10000,
        alpha=0.05,
        practical_threshold=None,
        practical_threshold_absolute=None,
        fdr=0.05,
        seed=20260101,
        higher_is_better=None,
        lower_is_better=None,
    )
    analysis = analyse_database(args, sensitivity=False)
    findings = [f for f in analysis.report.findings if f.result.candidate == "ngram_de_DE_val"]
    assert len(findings) == 1
    finding = findings[0]
    assert not finding.result.is_weak_mode, "five replicates must give the seed replicated mode"
    assert finding.result.higher_is_better
    assert finding.result.effect > 0.05, finding.result.effect
    assert finding.adjusted_p <= 0.05, finding.adjusted_p


