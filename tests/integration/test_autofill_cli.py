"""`triage autofill` end to end, and the sweep landing in the existing tool.

Acceptance criterion 1 is the point of this file: the sweep is generated by one
command, ingested by the command that already existed, and compared by the
command that already existed, with no flag naming autofill anywhere in the last
two. The test therefore drives `triage.cli.main` with real argument lists rather
than calling the library, because a contract that only holds when a Python
caller assembles it by hand is not the contract that was asked for.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from triage.cli import EXIT_OK, EXIT_USAGE, main


